const lines = (await readFile('artifacts/usda-selected.jsonl', 'utf8')).trim().split('\n')
const products = lines.map((line) => {
  const item = JSON.parse(line)
  const translation = names[item.id]
  if (!translation) throw new Error(`Нет русского описания для ${item.id}`)
  return {
    id: item.id,
    source: 'usda',
    sourceId: item.sourceId,
    name: translation[0],
    nameRu: translation[0],
    category: translation[1],
    note: 'USDA FoodData Central · лабораторный профиль на 100 г',
    nutrients: item.nutrients,
    raw: { emoji: translation[2], official: true, verified: true, originalName: item.originalName },
  }
})
if (products.length !== Object.keys(names).length) throw new Error(`Ожидалось ${Object.keys(names).length}, получено ${products.length}`)
await mkdir('server/data', { recursive: true })
